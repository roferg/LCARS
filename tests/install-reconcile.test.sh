check "6. install.sh contains no write to any shell profile name" \
  "! grep -nE '(>>|>|tee|sed -i)[^|]*(zshrc|bashrc|bash_profile|zprofile|/\\.profile)' '$INSTALL'"
check "6. install.sh writes only under its declared destinations (no \$HOME/ literals)" \
  "! grep -nE '^[^#]*>[[:space:]]*\"?\\\$HOME' '$INSTALL'"

# ==========================================================================
# Behaviour 6b — THE REGENERATION MECHANISM, found while measuring behaviour 6.
#
# "A session installed from its worktree" was only half the story. The other
# half is a TRACKED TEST SUITE: tests/install-copilot.test.sh ran install.sh
# with LCARS_SKILLS_DEST and the two Copilot variables set, but NOT
# LCARS_BIN_DEST — which therefore defaulted to $HOME/.local/bin. So a scoped,
# "isolated" run of that suite from any worktree silently rewrote all five of
# the captain's live on-PATH launchers to exec that worktree, and when the
# worktree went they all exited 127. MEASURED 2026-10-12 20:15:13: an
# install-suite run from ~/Projects/lcars-wt/s290 repointed every one of them.
#
# install.sh's own header says it in words — "setting only ONE of them does NOT
# isolate the install" — and a suite still did it, so the rule needs a test and
# not just a comment. Any suite that EXECUTES install.sh must redirect the
# launcher destination, by LCARS_BIN_DEST or LCARS_INSTALL_PREFIX, or by HOME.
# ==========================================================================
# S290 FIX ROUND 1 (D7) — the first cut of this guard had FOUR escape hatches,
# each measured against a planted probe:
#   (1) a file running `bash "$INSTALL"` with NO isolation whatsoever, which
#       merely MENTIONED `HOME=` in a comment, counted as isolated — the
#       isolation grep read the raw file, comments and all.
#   (2) `bash $REPO/install.sh` (UNQUOTED) was not detected as running
#       install.sh at all: the pattern required a double quote.
#   (3) `"$REPO_ROOT/install.sh"` (direct exec, no `bash`) was not detected.
#   (4) the isolation grep accepted the bare STRING `LCARS_BIN_DEST` with no
#       `=` at all, so a suite that only talked about the variable passed.
# So detection and isolation are now both done over LOGICAL lines (bash `\`
# continuations joined, comments stripped), detection covers the direct-exec
# and unquoted shapes, and isolation requires a real ASSIGNMENT. A read-only
# word list keeps the lines that merely grep/cp/stat install.sh out of it.

# S290 FIX ROUND 2 (R1-D3) — the round-1 guard decided isolation PER FILE, so
# one hatch survived: a suite containing a legitimate, unrelated
# `HOME="$t/other" bash some-other-tool.sh` ANYWHERE in it read as isolated even
# with a bare `bash "$INSTALL"` in it too, and many suites legitimately set HOME.
# A variable holding the path (`I="$REPO/install.sh"` then `bash "$I"`) escaped
# as well. So isolation is now decided PER LOGICAL LINE — the line that runs
# install.sh is the line that must carry the isolation — aliases are harvested,
# and HEREDOC BODIES are dropped (this very file writes unisolated probe files
# through heredocs; bash does not execute a heredoc body and neither does the
# guard).

# logical_lines <file> — the file as bash sees it: HEREDOC BODIES dropped,
# whole-line comments dropped, `\` continuations joined into one line, trailing
# ` # …` comments dropped.
# Joining matters: a real suite writes `env HOME=… \` on one line and
# `bash "$ck/install.sh"` on the next, and a `grep -rnE … \` command can carry
# `install.sh` onto a later line as a plain ARGUMENT.
logical_lines() {
  awk '
    # inside a heredoc body: that is DATA, not commands. Skip to the delimiter.
    inhd { t = $0; sub(/^[[:space:]]+/, "", t); if (t == tag) inhd = 0; next }
    {
      print
      # ...but a whole-line comment that happens to mention << opens nothing.
      if ($0 ~ /^[[:space:]]*#/) next
      if (match($0, "<<-?[[:space:]]*[\"\047]?[A-Za-z_][A-Za-z0-9_]*")) {
        d = substr($0, RSTART, RLENGTH)
        sub("^<<-?[[:space:]]*[\"\047]?", "", d)
        tag = d; inhd = 1
      }
    }
  ' "$1" \
    | sed 's/^[[:space:]]*#.*$//' \
    | awk '{ line = line $0
             if (line ~ /\\$/) { sub(/\\$/, "", line); next }
             print line; line = "" }
           END { if (line != "") print line }' \
    | sed 's/[[:space:]]#[[:space:]].*$//'
}

# Three shapes of "this line mentions OUR install.sh": $INSTALL / ${INSTALL},
# any path ending in /install.sh, or a command-position bare `install.sh`.
# `-install.sh` and `missing-install.sh` are deliberately NOT our install.sh.
GUARD_MENTION='(^|[^A-Za-z0-9_])\$\{?INSTALL\}?([^A-Za-z0-9_]|$)|/install\.sh|(^|[^A-Za-z0-9_./-])install\.sh'
# ...minus the lines that only READ it, or only name it in a string. ANY
# assignment line counts here, and so do the assertion/print verbs, because a
# genuine run through either shape is caught by GUARD_FORCE_RUN below, which
# OVERRIDES this list. That is what makes widening it safe.
GUARD_READONLY='(^|[^[:alnum:]_])(grep|egrep|fgrep|cp|mv|sed|awk|cat|wc|head|tail|diff|cmp|chmod|rm|ls|mkdir|printf|echo|shellcheck|dirname|basename|shasum|stat|find|touch|test|:|\[|check|ok|bad|qgrep)([[:space:]]|$)|bash[[:space:]]+-n|^[[:space:]]*(local[[:space:]]+|export[[:space:]]+)?[A-Za-z_][A-Za-z0-9_]*='
# Isolation must be an ASSIGNMENT to one of the three, not a mention of it.
GUARD_ISOLATION='(^|[^A-Za-z0-9_])(LCARS_BIN_DEST|LCARS_INSTALL_PREFIX|HOME)='

# guard_aliases <file> — variable names assigned a bare path that ENDS in
# install.sh, e.g. `I="$REPO/install.sh"`. These are second names for our
# install.sh, so `bash "$I"` is a run. Requiring a space-free right-hand side
# keeps prose assignments (MARKER='… generated by install.sh') out of it.
guard_aliases() {
  logical_lines "$1" \
    | sed -n 's/^[[:space:]]*\([A-Za-z_][A-Za-z0-9_]*\)=["'"'"']*[^[:space:]"'"'"']*install\.sh["'"'"']*[[:space:]]*$/\1/p' \
    | sort -u
}

# guard_mention_re <file> — GUARD_MENTION plus this file's own aliases.
guard_mention_re() {
  local a extra=""
  for a in $(guard_aliases "$1"); do
    extra="$extra|(^|[^A-Za-z0-9_])\\\$\\{?$a\\}?([^A-Za-z0-9_]|\$)"
  done
  printf '%s%s' "$GUARD_MENTION" "$extra"
}

# guard_force_re <file> — the shapes that EXECUTE our install.sh beyond argument:
# handing it to bash/sh/zsh (anywhere on the line, so `env … bash …` and
# `python3 cage.py N bash …` both count, while `bash -n` does not), or naming it
# in command position. A match here is a run REGARDLESS of GUARD_READONLY.
guard_force_re() {
  local a names="INSTALL"
  for a in $(guard_aliases "$1"); do names="$names|$a"; done
  printf '(^|[^A-Za-z0-9_])(ba|z)?sh[[:space:]]+("?\\$\\{?(%s)\\}?"?|"?[^[:space:]"]*/install\\.sh"?)([[:space:]]|$)|^[[:space:]]*("?[^[:space:]"]*/install\\.sh"?|"?\\$\\{?(%s)\\}?"?)([[:space:]]|$)' \
    "$names" "$names"
}

# guard_run_lines <file> — the LOGICAL LINES of <file> that run install.sh.
# NOTE: this CAPTURES instead of ending in `grep -q`. This suite runs under
# `set -o pipefail`, and a terminal `grep -q` exits on its first match, which
# SIGPIPEs the upstream sed/awk — so the whole pipeline reports failure and the
# round-1 `guard_isolated` said "not isolated" about a suite that plainly was.
# That bug made the guard flag THIS file. A command substitution drains the pipe.
# These are grep -E, deliberately, NOT awk: awk's DYNAMIC regexes go through
# string-escape processing first, which eats the backslash in `\$` and turns the
# whole pattern into an unmatchable "end of line followed by…". Measured while
# writing this: every real install-running line read `mention=0`.
guard_run_lines() {
  local m fr ll
  m="$(guard_mention_re "$1")"
  fr="$(guard_force_re "$1")"
  ll="$(logical_lines "$1")"
  {
    printf '%s\n' "$ll" | grep -E "$fr" || true
    printf '%s\n' "$ll" | grep -E "$m" | grep -vE "$GUARD_READONLY" \
      | grep -vE "$fr" || true
  }
}
guard_runs_install() { [ -n "$(guard_run_lines "$1")" ]; }

# guard_leaky_lines <file> — the run lines that do NOT carry isolation. PER LINE:
# the line that runs install.sh is the line that must redirect the destinations.
guard_leaky_lines() {
  local out
  out="$(guard_run_lines "$1" | grep -vE "$GUARD_ISOLATION" || true)"
  printf '%s' "$out"
}

# scan_leaky <dir> — names of *.test.sh in <dir> that run install.sh unisolated.
scan_leaky() {
  local f out=""
  for f in "$1"/*.test.sh; do
    [ -f "$f" ] || continue
    [ -n "$(guard_leaky_lines "$f")" ] || continue
    out="$out $(basename "$f")"
  done
  printf '%s' "$out"
}

