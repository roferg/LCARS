#!/usr/bin/env bash
#
# Session 290 — a stranger's first run works, and says why if it cannot.
#
# Three measured failures on the captain's own machine drive this suite. On
# 2026-10-12, a pre-flight snapshot found ALL FIVE of his `lcars-*` commands
# exiting 127:
#
#   lcars-eeh      -> .../lcars-wt/s278/skills/lcars-eeh/eeh.sh       MISSING
#   lcars-ech  -> .../lcars-wt/s278/skills/lcars-eeh/ech.sh   MISSING
#   lcars-viewscreen -> .../lcars-wt/s278/skills/lcars-viewscreen/...       MISSING
#   lcars-launch     -> .../lcars-wt/s278/skills/lcars-launch/launch.sh     MISSING
#   lcars-serve      -> .../lcars-wt/s278/skills/lcars-viewscreen/serve.sh  MISSING
#
# because a session had run `./install.sh` from its own worktree, baking that
# worktree's absolute paths into ~/.local/bin. When the worktree was deleted
# every command broke, and NOTHING anywhere said so — the launcher existed, was
# executable, and `exec bash`-ed a file that was not there.
#
# Repairing it measured the second half: `./install.sh` from `main` fixed only
# THREE of the five. `main` cannot reclaim `lcars-eeh`/`lcars-ech`
# because `main` does not itself generate those names. A reinstall is therefore
# not a repair, and the defect REGENERATES on every worktree install.
#
# So reconciliation must handle three cases, all covered below:
#   (a) a marked launcher whose NAME is no longer in the current set  -> remove
#   (b) a marked launcher whose name IS current but whose TARGET is gone
#       -> repoint at the installing checkout and SAY SO   (tonight's failure)
#   (c) a marked launcher pointing OUTSIDE the installing checkout, still
#       existing -> repoint and SAY SO (the latent form of (b))
#
# ...and it must only ever touch files bearing LCARS's own generated-by marker.
# The real-world control for that rule also lives on his machine: ~/.local/bin
# holds nine `cf-*` launchers belonging to a different project. They carry no
# LCARS marker and must survive everything here. This suite plants both an
# unmarked foreign `cf-*` script and an unmarked script with an LCARS name.
#
# EVERYTHING is isolated: temp prefixes, a fake $HOME, and a sha256 tripwire on
# the real dotfile NAMES (.zshrc/.bash_profile/.profile/.zprofile) so a single
# byte written to a shell profile fails this suite.
#
# Usage: bash tests/install-reconcile.test.sh
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INSTALL="$REPO_ROOT/install.sh"
MARKER='lcars-launcher: generated by install.sh'
MANIFEST_NAME='.lcars-launchers'

pass=0
fail=0
TMPROOT="$(mktemp -d "${TMPDIR:-.}/lcars-install-reconcile.XXXXXX")"
TMPROOT="$(cd "$TMPROOT" && pwd)"
trap 'rm -rf "$TMPROOT"' EXIT

ok()   { printf '  \033[32mPASS\033[0m %s\n' "$1"; pass=$((pass + 1)); }
bad()  { printf '  \033[31mFAIL\033[0m %s\n' "$1"; fail=$((fail + 1)); }
check(){ if eval "$2"; then ok "$1"; else bad "$1 ($2)"; fi; }

# --------------------------------------------------------------------------
# A fake LCARS checkout: real install.sh + real gen-copilot-plugin.sh, stub
# skills. `--small` drops the two launcher names that exist only on the branch,
# reproducing `main`'s launcher set exactly (that asymmetry IS the bug).
# --------------------------------------------------------------------------
make_checkout() {
  local dir="$1" small="${2:-}"
  mkdir -p "$dir/skills/lcars-viewscreen" "$dir/skills/lcars-launch" \
           "$dir/skills/lcars-eeh" "$dir/.claude-plugin"
  cp "$REPO_ROOT/gen-copilot-plugin.sh" "$dir/gen-copilot-plugin.sh"
  if [ -n "$small" ]; then
    grep -v 'install_launcher "lcars-eeh"' "$INSTALL" \
      | grep -v 'install_launcher "lcars-ech"' >"$dir/install.sh"
  else
    cp "$INSTALL" "$dir/install.sh"
  fi
  local tag; tag="$(basename "$dir")"
  local s
  for s in lcars-viewscreen/viewscreen.sh lcars-viewscreen/serve.sh \
           lcars-launch/launch.sh lcars-eeh/eeh.sh lcars-eeh/ech.sh; do
    printf '#!/usr/bin/env bash\necho "FAKE %s from %s"\n' "$(basename "$s")" "$tag" \
      >"$dir/skills/$s"
    chmod +x "$dir/skills/$s"
  done
}

new_prefix() { mktemp -d "$TMPROOT/pfx.XXXXXX"; }

# run_install <checkout> <prefix> <outfile> [extra-PATH] [argv...]
run_install() {
  local ck="$1" pfx="$2" out="$3" extra="${4:-}"; shift 4 || shift 3
  local fh="$pfx/fakehome"
  mkdir -p "$fh"
  env -u LCARS_SKILLS_DEST -u LCARS_BIN_DEST -u LCARS_COPILOT_PLUGINS_DIR \
      -u LCARS_COPILOT_CONFIG \
      HOME="$fh" \
      LCARS_INSTALL_PREFIX="$pfx/inst" \
      LCARS_COPILOT_BIN=/usr/bin/true \
      PATH="${extra:+$extra:}/usr/bin:/bin:/usr/sbin:/sbin" \
      bash "$ck/install.sh" "$@" >"$out" 2>&1
}

marked()   { [ -f "$1" ] && grep -q "$MARKER" "$1"; }
unmarked() { [ -f "$1" ] && ! grep -q "$MARKER" "$1"; }

echo "install (launcher reconciliation + uninstall)"
[ -f "$INSTALL" ] || { echo "install.sh not found at $INSTALL"; exit 1; }

CK_A="$TMPROOT/checkoutA"; make_checkout "$CK_A"
CK_SMALL="$TMPROOT/checkoutSmall"; make_checkout "$CK_SMALL" --small
CK_DOOMED="$TMPROOT/checkoutDoomed"; make_checkout "$CK_DOOMED"

# ==========================================================================
# Behaviour 1 — a manifest, and reconciliation case (a): install the full set,
# then install from a checkout whose launcher set is SMALLER. The dropped names
# must GO, and the install must say it removed them.
# ==========================================================================
p1="$(new_prefix)"; b1="$p1/inst/bin"
run_install "$CK_A" "$p1" "$p1/out1a.txt"

check "1. install writes a launcher manifest beside the launchers" \
  "[ -f '$b1/$MANIFEST_NAME' ]"
check "1. the manifest lists every launcher name it created" \
  "grep -qx 'lcars-viewscreen' '$b1/$MANIFEST_NAME' \
   && grep -qx 'lcars-serve'    '$b1/$MANIFEST_NAME' \
   && grep -qx 'lcars-launch'   '$b1/$MANIFEST_NAME' \
   && grep -qx 'lcars-eeh'    '$b1/$MANIFEST_NAME' \
   && grep -qx 'lcars-ech' '$b1/$MANIFEST_NAME'"

# a foreign project's launcher (the real nine cf-* commands) and a user's own
# script that happens to share an LCARS name — both UNMARKED.
printf '#!/bin/sh\necho cf-plan is not lcars\n' >"$b1/cf-plan"; chmod +x "$b1/cf-plan"
printf '#!/bin/sh\necho my own ECH\n'     >"$b1/lcars-ech.user"
cf_sha="$(shasum -a 256 "$b1/cf-plan" | awk '{print $1}')"

run_install "$CK_SMALL" "$p1" "$p1/out1b.txt"

check "1. (a) a marked launcher no longer in the current set is REMOVED" \
  "[ ! -e '$b1/lcars-eeh' ] && [ ! -e '$b1/lcars-ech' ]"
check "1. (a) the install SAYS which stale launchers it removed" \
  "grep -q 'lcars-eeh' '$p1/out1b.txt' && grep -qi 'removed' '$p1/out1b.txt'"
check "1. (a) the launchers still in the set survive and point at the new checkout" \
  "grep -q '$CK_SMALL/skills/lcars-viewscreen/viewscreen.sh' '$b1/lcars-viewscreen' \
   && [ -x '$b1/lcars-serve' ] && [ -x '$b1/lcars-launch' ]"
check "1. (a) the manifest now lists exactly the three current names" \
  "[ \"\$(grep -c . '$b1/$MANIFEST_NAME')\" -eq 3 ] && ! grep -qx 'lcars-eeh' '$b1/$MANIFEST_NAME'"
check "1. (a) the foreign cf-plan launcher is byte-for-byte untouched" \
  "[ \"\$(shasum -a 256 '$b1/cf-plan' | awk '{print \$1}')\" = '$cf_sha' ]"

# ==========================================================================
# Behaviour 2 — the control that makes rule 1 safe: a user-owned script with an
# LCARS name but NO marker survives reconciliation, and is named, not deleted.
# ==========================================================================
p2="$(new_prefix)"; b2="$p2/inst/bin"
run_install "$CK_A" "$p2" "$p2/out2a.txt"
printf '#!/bin/sh\necho MINE not lcars\n' >"$b2/lcars-ech"; chmod +x "$b2/lcars-ech"
mine_sha="$(shasum -a 256 "$b2/lcars-ech" | awk '{print $1}')"
run_install "$CK_SMALL" "$p2" "$p2/out2b.txt"

check "2. an UNMARKED script with an LCARS name survives reconciliation" \
  "[ -f '$b2/lcars-ech' ] && unmarked '$b2/lcars-ech' \
   && [ \"\$(shasum -a 256 '$b2/lcars-ech' | awk '{print \$1}')\" = '$mine_sha' ]"
check "2. ...and reconciliation says it left the unmarked file alone" \
  "grep -q 'lcars-ech' '$p2/out2b.txt' && grep -qi 'not an LCARS launcher\|left alone\|not ours' '$p2/out2b.txt'"

# ==========================================================================
# Behaviour 3 — the PATH problem. Loud block with BOTH routes when the bin dir
# is off PATH; silent when it is on.
# ==========================================================================
p3="$(new_prefix)"; b3="$p3/inst/bin"
run_install "$CK_A" "$p3" "$p3/out3.txt"
check "3. off PATH: the message names the exact export line" \
  "grep -qF 'export PATH=\"$b3:\$PATH\"' '$p3/out3.txt'"
check "3. off PATH: the message gives the no-PATH fallback as an absolute bash command" \
  "grep -qF 'bash $CK_A/skills/lcars-eeh/eeh.sh' '$p3/out3.txt'"
check "3. off PATH: the block is impossible to miss (ACTION NEEDED banner)" \
  "grep -qi 'ACTION NEEDED' '$p3/out3.txt'"

p3b="$(new_prefix)"
run_install "$CK_A" "$p3b" "$p3b/out3b.txt" "$p3b/inst/bin"
check "3. on PATH: no add-to-PATH block at all" \
  "! grep -qi 'ACTION NEEDED\|export PATH' '$p3b/out3b.txt'"

# ==========================================================================
# Behaviour 4 — the fallback command, copied VERBATIM out of the message,
# actually runs the EEH. (Extracted by grep, not retyped.)
# ==========================================================================
fallback="$(grep -oE "bash $CK_A/skills/lcars-eeh/eeh\.sh" "$p3/out3.txt" | head -1)"
fb_repo="$TMPROOT/fbrepo"; mkdir -p "$fb_repo"; ( cd "$fb_repo" && git init -q 2>/dev/null )
fb_out="$( LCARS_REPO="$CK_A" LCARS_EEH_CWD="$fb_repo" eval "$fallback" 2>&1 )"
check "4. the no-PATH fallback command from the message runs the EEH" \
  "[ -n '$fallback' ] && printf '%s' \"\$fb_out\" | grep -q 'FAKE eeh.sh from checkoutA'"

# the same fallback shape against the REAL repo, so the printed path is the real
# the EEH and not only a stub: a known-good control for the check above.
real_fb_out="$( LCARS_REPO="$REPO_ROOT" LCARS_EEH_CWD="$fb_repo" \
                LCARS_SKILLS_DEST="$TMPROOT/nonexistent-skills" \
                bash "$REPO_ROOT/skills/lcars-eeh/eeh.sh" 2>&1 )"
check "4. CONTROL: the same command shape runs the REAL EEH from this repo" \
  "printf '%s' \"\$real_fb_out\" | grep -q 'LCARS EEH — the Emergency Engineering Hologram'"

# ==========================================================================
# Behaviour 7 — THE LIVE FAILURE, as a regression test. A marked launcher whose
# checkout has been DELETED must (i) say why instead of a bare 127, and (ii) be
# repointed at the installing checkout by the next install, and then RUN.
# ==========================================================================
p7="$(new_prefix)"; b7="$p7/inst/bin"
run_install "$CK_DOOMED" "$p7" "$p7/out7a.txt"
check "7. pre-condition: the launcher ran from the doomed checkout" \
  "[ \"\$('$b7/lcars-eeh' 2>&1)\" = 'FAKE eeh.sh from checkoutDoomed' ]"

rm -rf "$CK_DOOMED"
dangling_out="$("$b7/lcars-eeh" 2>&1)"; dangling_rc=$?
check "7. a launcher whose checkout is gone fails with WORDS, not a bare 127" \
  "[ $dangling_rc -ne 0 ] \
   && printf '%s' \"\$dangling_out\" | grep -q 'lcars-eeh' \
   && printf '%s' \"\$dangling_out\" | grep -qi 'no longer exists\|does not exist' \
   && printf '%s' \"\$dangling_out\" | grep -qi 'install.sh'"

run_install "$CK_A" "$p7" "$p7/out7b.txt"
check "7. (b) the next install REPOINTS it at the installing checkout" \
  "grep -q '$CK_A/skills/lcars-eeh/eeh.sh' '$b7/lcars-eeh'"
check "7. (b) ...and the repointed launcher actually RUNS" \
  "[ \"\$('$b7/lcars-eeh' 2>&1)\" = 'FAKE eeh.sh from checkoutA' ]"
check "7. (b) ...and the install SAID it repointed a launcher whose checkout was gone" \
  "grep -qi 'no longer exists' '$p7/out7b.txt' && grep -qi 'repoint' '$p7/out7b.txt'"

# ==========================================================================
# Behaviour 8 — case (c): a marked launcher pointing into a DIFFERENT, still
# existing checkout. PINNED BEHAVIOUR: repoint it at the installing checkout
# AND report the old path. Rationale: silently leaving it means the install the
# user just ran did not take effect, which is the exact confusion this session
# cures; and repointing is already the historic behaviour, so warn-only would
# be a regression.
# ==========================================================================
CK_B="$TMPROOT/checkoutB"; make_checkout "$CK_B"
p8="$(new_prefix)"; b8="$p8/inst/bin"
run_install "$CK_B" "$p8" "$p8/out8a.txt"
run_install "$CK_A" "$p8" "$p8/out8b.txt"
check "8. (c) a launcher pointing at another live checkout is repointed here" \
  "grep -q '$CK_A/skills/lcars-viewscreen/viewscreen.sh' '$b8/lcars-viewscreen'"
check "8. (c) ...and the install reports the repoint, naming the OLD checkout" \
  "grep -qi 'repoint' '$p8/out8b.txt' && grep -q '$CK_B' '$p8/out8b.txt'"
check "8. (c) a same-checkout re-install reports NO repoint (no false alarm)" \
  "run_install '$CK_A' '$p8' '$p8/out8c.txt'; ! grep -qi 'repoint' '$p8/out8c.txt'"

# ==========================================================================
# Behaviour 9 — the honest PASS/FAIL line. It must be produced by TESTING
# resolution, never by asserting it.
# ==========================================================================
p9="$(new_prefix)"
run_install "$CK_A" "$p9" "$p9/out9a.txt" "$p9/inst/bin"
check "9. with the bin dir on PATH the install ends with a tested READY verdict" \
  "grep -q 'READY' '$p9/out9a.txt' && ! grep -q 'NOT READY' '$p9/out9a.txt'"
check "9. the READY line says the resolution was actually TESTED" \
  "grep -qi 'tested\|ran it\|verified' '$p9/out9a.txt'"

check "9. with the bin dir OFF PATH the verdict is NOT READY and names the cure" \
  "grep -q 'NOT READY' '$p3/out3.txt' && grep -qi 'PATH' '$p3/out3.txt'"

# the honesty control: bin dir IS on PATH, but an earlier PATH entry SHADOWS
# our launcher with a foreign script. A verdict that merely asserts would say
# READY; one that resolves and runs must say NOT READY and name the shadow.
shadow="$TMPROOT/shadowbin"; mkdir -p "$shadow"
printf '#!/bin/sh\necho not lcars at all\nexit 3\n' >"$shadow/lcars-eeh"
chmod +x "$shadow/lcars-eeh"
p9c="$(new_prefix)"
run_install "$CK_A" "$p9c" "$p9c/out9c.txt" "$shadow:$p9c/inst/bin"
check "9. CONTROL: a shadowed launcher reads NOT READY and names the shadow" \
  "grep -q 'NOT READY' '$p9c/out9c.txt' && grep -q '$shadow/lcars-eeh' '$p9c/out9c.txt'"

# ==========================================================================
# Behaviour 5 — uninstall. Removes exactly the marked launchers + both skill
# farms + the Copilot plugin registration, says what went, is idempotent, and
# refuses to delete anything unmarked.
# ==========================================================================
p5="$(new_prefix)"; b5="$p5/inst/bin"
run_install "$CK_A" "$p5" "$p5/out5a.txt"
printf '#!/bin/sh\necho cf-review\n' >"$b5/cf-review"; chmod +x "$b5/cf-review"
printf '#!/bin/sh\necho mine\n' >"$b5/lcars-serve.mine"
# a user's own REAL directory in the skills farm must not be collateral
mkdir -p "$p5/inst/claude-skills/someones-own-skill"
printf 'x\n' >"$p5/inst/claude-skills/someones-own-skill/SKILL.md"
cfr_sha="$(shasum -a 256 "$b5/cf-review" | awk '{print $1}')"

check "5. pre-condition: the copilot plugin + config entry exist before uninstall" \
  "[ -L '$p5/inst/copilot-plugins/lcars' ] && grep -q '\"lcars\"' '$p5/inst/copilot-config.json'"

run_install "$CK_A" "$p5" "$p5/out5b.txt" "" uninstall; rc5=$?
check "5. uninstall exits 0" "[ $rc5 -eq 0 ]"
check "5. uninstall removed every marked launcher and the manifest" \
  "[ ! -e '$b5/lcars-viewscreen' ] && [ ! -e '$b5/lcars-serve' ] \
   && [ ! -e '$b5/lcars-launch' ] && [ ! -e '$b5/lcars-eeh' ] \
   && [ ! -e '$b5/lcars-ech' ] && [ ! -e '$b5/$MANIFEST_NAME' ]"
check "5. uninstall left the UNMARKED foreign launcher byte-identical" \
  "[ \"\$(shasum -a 256 '$b5/cf-review' | awk '{print \$1}')\" = '$cfr_sha' ]"
check "5. uninstall removed the Claude skill farm's lcars symlinks" \
  "[ \"\$(find '$p5/inst/claude-skills' -maxdepth 1 -type l | wc -l | tr -d ' ')\" -eq 0 ]"
check "5. uninstall left a user's own real skill dir alone" \
  "[ -f '$p5/inst/claude-skills/someones-own-skill/SKILL.md' ]"
check "5. uninstall removed the Copilot plugin symlink" \
  "[ ! -e '$p5/inst/copilot-plugins/lcars' ]"
check "5. uninstall dropped the lcars entry from the Copilot config" \
  "! grep -q '\"lcars\"' '$p5/inst/copilot-config.json'"
check "5. uninstall SAYS what it removed (counts or names)" \
  "grep -qi 'removed' '$p5/out5b.txt' && grep -q 'lcars-viewscreen' '$p5/out5b.txt'"

run_install "$CK_A" "$p5" "$p5/out5c.txt" "" uninstall; rc5b=$?
check "5. a second uninstall is a clean no-op (exit 0, says nothing to remove)" \
  "[ $rc5b -eq 0 ] && grep -qi 'nothing to remove\|already' '$p5/out5c.txt'"
check "5. the second uninstall still did not touch the unmarked launcher" \
  "[ \"\$(shasum -a 256 '$b5/cf-review' | awk '{print \$1}')\" = '$cfr_sha' ]"

# ==========================================================================
# Behaviour 6 — NOTHING outside the repo and the install prefix is written. The
