# Behaviour 18 — S290 FIX ROUND 2, R1-D1: THE INJECTION CLASS, AT THE CLASS.
#
# Round 1 removed the hardcoded backtick install.sh itself wrote, but the baked
# CHECKOUT PATH was still interpolated into DOUBLE-quoted strings in the
# generated launcher (generated lines 11, 13, 24, 28), so the path could bring
# its own shell. Measured over seven hostile checkouts, two broke:
#   …/back`tick/   -> bash ran `tick`; the printed path was truncated to …/back
#   …/dol$lar/     -> $lar expanded to empty and the launcher was BROKEN WHILE
#                     THE CHECKOUT STILL EXISTED (exit 127, nothing deleted)
# Re-measured here after the cure over a WIDER set — the two that broke plus
# $(…), a double quote, a single quote, a space, !, ;, parens, a backslash and a
# NEWLINE — because the fix is at the class (emit the target ONCE as an inert
# single-quoted literal), so the proof must be at the class too.
#
# Each path is proven twice: byte-identical argument pass-through through the
# launcher, and the dangling-target guard still exiting 127 with the command
# NAMED. Those are the two things the cure must not cost.
# ==========================================================================
want18="ARGS[a b][\$HOME][quo'te][semi;colon][][ta$(printf '\t')b]"
h18=0
for hname in 'back`tick' 'dol$lar' 'sub$(id)' "quo'te" 'dou"ble' 'sp ace' \
             'bang!' 'semi;colon' 'par(en)' 'back\slash' "$(printf 'new\nline')"; do
  h18=$((h18 + 1))
  lbl="$(printf '%s' "$hname" | tr '\n' '?')"
  hroot="$TMPROOT/hostile$h18"
  if ! mkdir -p "$hroot/$hname" 2>/dev/null; then
    check "18. [$lbl] this filesystem refuses the path, so nothing can be injected from it" "true"
    continue
  fi
  hck="$hroot/$hname"
  make_checkout "$hck"
  cat >"$hck/skills/lcars-eeh/eeh.sh" <<'STUB'
#!/usr/bin/env bash
printf 'ARGS'
for a in "$@"; do printf '[%s]' "$a"; done
printf '\n'
STUB
  chmod +x "$hck/skills/lcars-eeh/eeh.sh"
  ph="$(new_prefix)"
  run_install "$hck" "$ph" "$ph/out.txt"
  L18="$ph/inst/bin/lcars-eeh"
  if [ ! -f "$L18" ]; then
    check "18. [$lbl] a launcher was generated at all" "false"
    continue
  fi
  # the target is baked as an inert SINGLE-QUOTED literal, not interpolated.
  check "18. [$lbl] the baked target is a single-quoted literal" \
    "grep -q \"^LCARS_LAUNCHER_TARGET='\" '$L18'"
  got18="$(env -i PATH=/usr/bin:/bin HOME="$ph/fakehome" python3 "$CAGE" 8 \
             "$L18" 'a b' '$HOME' "quo'te" 'semi;colon' '' "$(printf 'ta\tb')" \
             2>&1 | grep '^ARGS' || true)"
  check "18. [$lbl] the launcher RUNS and passes arguments byte-identically" \
    "[ \"\$got18\" = \"\$want18\" ]"
  # ...and the dangling-target guard, the thing the hostile path broke first.
  mv "$hroot" "$hroot.gone"
  dout18="$(env -i PATH=/usr/bin:/bin HOME="$ph/fakehome" python3 "$CAGE" 8 \
              "$L18" 2>&1)"; drc18=$?
  check "18. [$lbl] with the checkout gone it exits 127 and NAMES the command (exit $drc18)" \
    "[ $drc18 -eq 127 ] && printf '%s' \"\$dout18\" | grep -qF \"lcars: 'lcars-eeh' points at\""
  # NB: the hostile string goes through a VARIABLE, never into the eval'd
  # expression — a path containing a single quote would close the quoting.
  hfirst18="$(printf '%s' "$hname" | head -1)"
  check "18. [$lbl] ...and the path it prints is the WHOLE path, not a truncation" \
    "printf '%s' \"\$dout18\" | grep -qF \"\$hfirst18\""
done
